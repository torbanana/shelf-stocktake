// Generates the fluffy Maltese silhouette used by src/components/Pup.tsx and public/favicon.svg.
// The outline is a polygon of key points with small circles along every edge, drawn twice
// (fat black, then white) so the result is one white shape with a thick wavy outline.
import { writeFileSync } from 'node:fs';

// Clockwise around the dog, 120x120 box. Head top -> right ear -> right arm -> right leg -> left leg -> left arm -> left ear.
const P = [
  [46, 16], [60, 12], [74, 16], [86, 24], [93, 36],
  [97, 46], [99, 58], [94, 66],
  [96, 72], [106, 68], [110, 74], [102, 82], [92, 84],
  [90, 92], [92, 102], [88, 110], [78, 110], [74, 100],
  [66, 98], [58, 100],
  [54, 110], [42, 110], [40, 100], [42, 90],
  [34, 86], [22, 84], [14, 78], [18, 70], [30, 68],
  [26, 62], [22, 54], [24, 42],
  [30, 30], [38, 20],
];

const circles = [];
for (let i = 0; i < P.length; i++) {
  const [x1, y1] = P[i];
  const [x2, y2] = P[(i + 1) % P.length];
  const len = Math.hypot(x2 - x1, y2 - y1);
  const n = Math.max(1, Math.round(len / 5));
  for (let k = 0; k < n; k++) {
    const t = k / n;
    const r = (i + k) % 2 === 0 ? 3.9 : 3.0;
    circles.push([+(x1 + (x2 - x1) * t).toFixed(1), +(y1 + (y2 - y1) * t).toFixed(1), r]);
  }
}
const poly = P.map(([x, y]) => `${x},${y}`).join(' ');

writeFileSync(
  'src/components/pupShapes.ts',
  `// Generated by scripts/make-pup.mjs. Do not edit by hand.\nexport const PUP_POLY = '${poly}';\nexport const PUP_CIRCLES: [number, number, number][] = ${JSON.stringify(circles)};\n`,
);

const blobs = `<polygon points="${poly}"/>` + circles.map(([x, y, r]) => `<circle cx="${x}" cy="${y}" r="${r}"/>`).join('');
const face = `<g fill="#111"><circle cx="47" cy="42" r="2.6"/><circle cx="71" cy="40" r="2.6"/><path d="M55.5 48h7a1.4 1.4 0 0 1 1.1 2.2l-3.5 4a1.4 1.4 0 0 1-2.2 0l-3.5-4a1.4 1.4 0 0 1 1.1-2.2z"/><path d="M49.5 55h19a9.5 9.5 0 0 1-19 0z"/></g><path d="M54 59h10a5 5 0 0 1-10 0z" fill="#f0616f"/>`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120">
<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#172043"/><stop offset="1" stop-color="#2b3a74"/></linearGradient><g id="blobs">${blobs}</g></defs>
<rect width="120" height="120" rx="28" fill="url(#sky)"/>
<g fill="#fff"><circle cx="14" cy="20" r="1.5"/><circle cx="28" cy="10" r="1"/><circle cx="104" cy="16" r="1.3"/><circle cx="12" cy="44" r="1"/><circle cx="110" cy="50" r="1.1"/><circle cx="20" cy="104" r="1"/><circle cx="108" cy="100" r="1"/></g>
<path d="M108 12l1.3 2.8 3 .4-2.2 2.1.6 3-2.7-1.4-2.7 1.4.6-3-2.2-2.1 3-.4z" fill="#ffd54f"/>
<g id="pup" transform="translate(-2 4)"><use href="#blobs" fill="#111" stroke="#111" stroke-width="5" stroke-linejoin="round"/><use href="#blobs" fill="#fff"/>${face}</g>
</svg>
`;
writeFileSync('public/favicon.svg', svg);
console.log('circles', circles.length);
